use crate::candidate::Candidate;
use crate::capabilities::{host_platform_kernel_string, ExecutionEvidenceReport};
use crate::config::{EnforcementMode, SandboxConfig};
use crate::platform;
use crate::supervisor::ProcessSupervisor;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::time::{Duration, Instant};

#[derive(Debug, Clone)]
pub struct RunOutput {
    pub stdout: String,
    pub stderr: String,
    pub exit_code: Option<i32>,
    pub duration: Duration,
    pub timed_out: bool,
}

#[derive(Debug, Clone)]
pub struct CompilationOutput {
    pub binary_path: PathBuf,
    pub binary_size_bytes: u64,
    pub compile_duration: Duration,
}

pub struct SandboxRunner {
    sandbox_base: PathBuf,
    run_id: String,
    timeout: Duration,
    max_output_bytes: usize,
    memory_ceiling_bytes: usize,
    enforcement_mode: EnforcementMode,
    env_vars: Vec<(String, String)>,
    last_evidence: Mutex<Option<ExecutionEvidenceReport>>,
    last_overflow: Mutex<Option<(&'static str, usize)>>,
}

impl SandboxRunner {
    /// Creates a new `SandboxRunner`. Defaults to `EnforcementMode::Strict` (fail-closed)
    /// so untrusted execution is refused whenever host isolation cannot be verified.
    pub fn new(run_id: String) -> Self {
        let sandbox_base = std::env::temp_dir().join("syntra_sandbox").join(&run_id);
        Self {
            sandbox_base,
            run_id,
            timeout: Duration::from_secs(5),
            max_output_bytes: 1024 * 1024, // 1 MB
            memory_ceiling_bytes: 128 * 1024 * 1024,
            enforcement_mode: EnforcementMode::Strict,
            env_vars: Vec::new(),
            last_evidence: Mutex::new(None),
            last_overflow: Mutex::new(None),
        }
    }

    pub fn with_timeout(mut self, timeout: Duration) -> Self {
        self.timeout = timeout;
        self
    }

    pub fn with_max_output_bytes(mut self, max: usize) -> Self {
        self.max_output_bytes = max;
        self
    }

    pub fn with_memory_ceiling_bytes(mut self, bytes: usize) -> Self {
        self.memory_ceiling_bytes = bytes;
        self
    }

    pub fn with_enforcement_mode(mut self, mode: EnforcementMode) -> Self {
        self.enforcement_mode = mode;
        self
    }

    pub fn with_env_var(mut self, key: String, value: String) -> Self {
        self.env_vars.push((key, value));
        self
    }

    pub fn timeout(&self) -> Duration {
        self.timeout
    }

    pub fn max_output_bytes(&self) -> usize {
        self.max_output_bytes
    }

    pub fn enforcement_mode(&self) -> EnforcementMode {
        self.enforcement_mode
    }

    pub fn run_id(&self) -> &str {
        &self.run_id
    }

    pub fn sandbox_base(&self) -> &Path {
        &self.sandbox_base
    }

    /// Prepares an isolated directory for the candidate.
    pub fn candidate_dir(&self, candidate_id: &str) -> PathBuf {
        self.sandbox_base.join(candidate_id)
    }

    /// Returns the structured evidence report generated by the latest `execute_binary` call.
    pub fn last_evidence_report(&self) -> Option<ExecutionEvidenceReport> {
        self.last_evidence.lock().ok().and_then(|g| g.clone())
    }

    /// Returns whether the latest execution tripped a stream output budget.
    pub fn last_stream_overflow(&self) -> Option<(&'static str, usize)> {
        self.last_overflow.lock().ok().and_then(|g| *g)
    }

    /// Compiles a candidate's AIR module to an isolated native binary.
    pub fn compile_candidate(&self, candidate: &Candidate) -> Result<CompilationOutput, String> {
        let dir = self.candidate_dir(&candidate.id);
        fs::create_dir_all(&dir).map_err(|e| {
            format!(
                "Failed to create candidate sandbox dir '{}': {}",
                dir.display(),
                e
            )
        })?;

        let obj_path = dir.join("candidate.o");
        let bin_path = dir.join("candidate_bin");

        let t0 = Instant::now();

        // 1. Compile AIR to machine code object file via Cranelift backend.
        syntra_backend_cranelift::compile_module_to_object(&candidate.air_module, &obj_path)
            .map_err(|e| {
                format!(
                    "Cranelift object compilation failed for {}: {}",
                    candidate.id, e
                )
            })?;

        // 2. Link executable with system linker and runtime.
        syntra_backend_cranelift::link_executable(&obj_path, &bin_path)
            .map_err(|e| format!("Linking executable failed for {}: {}", candidate.id, e))?;

        let compile_duration = t0.elapsed();

        // Clean up temporary .o.
        let _ = fs::remove_file(&obj_path);

        let binary_size_bytes = fs::metadata(&bin_path).map(|m| m.len()).unwrap_or(0);

        Ok(CompilationOutput {
            binary_path: bin_path,
            binary_size_bytes,
            compile_duration,
        })
    }

    /// Executes the candidate binary via the platform `SandboxProvider` and
    /// `ProcessSupervisor`, enforcing Strict fail-closed invariants by default.
    pub fn execute_binary(&self, binary_path: &Path, args: &[String]) -> Result<RunOutput, String> {
        let mut config = SandboxConfig::new(self.run_id.clone());
        config.sandbox_base = self.sandbox_base.clone();
        config.enforcement_mode = self.enforcement_mode;
        config.wall_clock_timeout = self.timeout;
        config.memory_allocation_ceiling_bytes = self.memory_ceiling_bytes;
        config.streams.stdout_limit_bytes = self.max_output_bytes;
        config.streams.stderr_limit_bytes = self.max_output_bytes;
        config.env_vars = self.env_vars.clone();

        let provider = platform::default_provider(&self.run_id);

        if config.enforcement_mode == EnforcementMode::Strict {
            provider
                .capabilities()
                .verify_strict_admissibility()
                .map_err(|e| e.to_string())?;
        }

        if !binary_path.exists() {
            return Err(format!("Binary does not exist: {}", binary_path.display()));
        }

        let mut child = provider
            .spawn(binary_path, args, &config)
            .map_err(|e| e.to_string())?;

        let supervised =
            ProcessSupervisor::supervise(&mut *child, &config.streams, config.wall_clock_timeout)
                .map_err(|e| e.to_string())?;

        if let Ok(mut guard) = self.last_overflow.lock() {
            *guard = supervised.stream_overflow;
        }

        let exit_status = if let Some(ref tel_err) = supervised.telemetry_error {
            format!("TelemetryError({tel_err})")
        } else if supervised.timed_out {
            "TimedOut".to_string()
        } else if let Some((s, lim)) = supervised.stream_overflow {
            format!("StreamOverflow({s}>{lim})")
        } else if let Some(code) = supervised.exit_code {
            format!("Exited({code})")
        } else {
            "Signaled".to_string()
        };

        let report = ExecutionEvidenceReport {
            schema_version: "1.0.0",
            execution_id: self.run_id.clone(),
            platform_os: std::env::consts::OS,
            kernel_release: host_platform_kernel_string(),
            enforcement_mode: self.enforcement_mode,
            memory_max_bytes: config.memory_allocation_ceiling_bytes,
            swap_max_bytes: 0,
            pids_max: config.max_pids,
            stdout_limit_bytes: config.streams.stdout_limit_bytes,
            stderr_limit_bytes: config.streams.stderr_limit_bytes,
            capabilities: supervised.evidence,
            exit_status,
            cleanup: supervised.cleanup,
        };
        if let Ok(mut guard) = self.last_evidence.lock() {
            *guard = Some(report);
        }

        if let Some(tel_err) = supervised.telemetry_error {
            return Err(tel_err.to_string());
        }

        Ok(RunOutput {
            stdout: supervised.stdout,
            stderr: supervised.stderr,
            exit_code: supervised.exit_code,
            duration: supervised.duration,
            timed_out: supervised.timed_out,
        })
    }

    /// Clean up the entire sandbox directory for this run.
    pub fn cleanup(&self) {
        let _ = fs::remove_dir_all(&self.sandbox_base);
    }
}

impl Drop for SandboxRunner {
    fn drop(&mut self) {
        self.cleanup();
    }
}
